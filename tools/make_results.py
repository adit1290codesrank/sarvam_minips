"""Regenerate RESULTS.md: run every reporting command and paste its output under it.

    python tools/make_results.py
"""
import glob
import json
import os
import platform
import subprocess
import sys

import soundfile as sf

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PY = sys.executable


def run(cmd):
    r = subprocess.run([PY] + cmd.split()[1:], cwd=ROOT, capture_output=True, text=True)
    return (r.stdout if r.returncode == 0 else r.stdout + r.stderr).strip()


def clips_table():
    lines = ["| clip | duration s | words | sentences | entities (gold) | negations | self-repairs |", "|---|---|---|---|---|---|---|"]
    for p in sorted(glob.glob(os.path.join(ROOT, "transcripts/L1/clip*.txt"))):
        c = os.path.basename(p)[:-4]
        wav = os.path.join(ROOT, "clips/16k", c + ".wav")
        words = sum(len(l.split()) for l in open(p, encoding="utf-8"))
        sents = sum(1 for l in open(p, encoding="utf-8") if l.strip())
        gp = os.path.join(ROOT, "checker/gold", c + ".json")
        gold = json.load(open(gp, encoding="utf-8")) if os.path.exists(gp) else []
        lines.append(f"| {c} | {sf.info(wav).duration:.1f} | {words} | {sents} | "
                     f"{sum(e['type'] != 'NEG' for e in gold)} | {sum(e['type'] == 'NEG' for e in gold)} | "
                     f"{sum(e.get('status') == 'corrected' for e in gold)} |")
    return "\n".join(lines)


def main():
    commit = subprocess.run(["git", "describe", "--always", "--dirty"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    try:
        import torch
        env = f"torch {torch.__version__} · {torch.cuda.get_device_name(0) if torch.cuda.is_available() else 'CPU'}"
    except ImportError:
        env = "torch not installed"
    sections = [
        ("D1 Clips", "python tools/make_results.py", clips_table()),
        ("D3–D4 Alignment: 30 hand-marked boundaries vs MMS_FA", "python align/eval_boundaries.py", run("python align/eval_boundaries.py")),
        ("D5–D6 Checker vs human verdicts, and entity preservation per system", "python checker/eval_checker.py eval",
         run("python checker/eval_checker.py eval")),
        ("E (ML track): wait-k on the clips' timeline", "python partE_ml/wait_k.py",
         open(os.path.join(ROOT, "partE_ml/out/results.md")).read().strip() + "\n\n![accuracy vs lag](partE_ml/out/acc_vs_lag.png)"
         if os.path.exists(os.path.join(ROOT, "partE_ml/out/results.md")) else "not run yet"),
        ("Tests", "python tests/test_checker.py && python prototypes/test_hindi_number_parser.py && python partE_ml/wait_k.py --test",
         "\n".join([run("python tests/test_checker.py"), run("python prototypes/test_hindi_number_parser.py"),
                    run("python partE_ml/wait_k.py --test")])),
    ]
    out = [f"# RESULTS\n\nCommit {commit} · Python {platform.python_version()} · {env}\n",
           "Every table below is regenerated by `make results`; the command under each heading reproduces it alone.\n"]
    for title, cmd, body in sections:
        out.append(f"## {title}\n\n`{cmd}`\n\n{body}\n")
    out.append(open(os.path.join(ROOT, "tools/limitations.md"), encoding="utf-8").read())
    open(os.path.join(ROOT, "RESULTS.md"), "w", encoding="utf-8").write("\n".join(out))
    print("RESULTS.md written")


if __name__ == "__main__":
    main()
